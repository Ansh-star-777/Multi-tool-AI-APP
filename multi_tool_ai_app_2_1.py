# ============================================================

def generate_response(prompt, temperature=0.3, max_tokens=1024):
    provider = st.session_state.get("provider", "Groq")

    if provider == "Groq":
        if not GROQ_API_KEY:
            return (
                "API key missing. Open your Streamlit Cloud app settings, "
                "select Secrets, and add GROQ_API_KEY."
            )

        client = OpenAI(
            api_key=GROQ_API_KEY,
            base_url=GROQ_URL,
            timeout=60,
            max_retries=1,
        )

        errors = []

        for model in GROQ_MODELS:
            try:
                result = client.chat.completions.create(
                    model=model,
                    messages=[
                        {"role": "user", "content": prompt}
                    ],
                    temperature=temperature,
                    max_tokens=max_tokens,
                )

                return (
                    result.choices[0].message.content
                    or "The AI returned an empty response."
                )

            except Exception as e:
                errors.append(f"{model}: {type(e).__name__}: {e}")

        return (
            "Groq could not complete the request. Check your API key, "
            "model access, and usage limits.\n\n"
            + "\n".join(errors)
        )

    if not HF_API_KEY:
        return (
            "HF_API_KEY is missing. Add it in Streamlit Cloud Secrets, "
            "or select Groq in the sidebar."
        )

    try:
        client = InferenceClient(
            model=HF_MODEL,
            token=HF_API_KEY,
            timeout=60,
        )

        result = client.chat_completion(
            messages=[
                {"role": "user", "content": prompt}
            ],
            temperature=temperature,
            max_tokens=max_tokens,
        )

        return (
            result.choices[0].message.content
            or "The AI returned an empty response."
        )

    except Exception as e:
        return (
            "Hugging Face request failed. Check your token and model "
            f"access.\n{type(e).__name__}: {e}"
        )


