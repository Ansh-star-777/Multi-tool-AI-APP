TEACH_SYSTEM = r"""
You are a helpful AI Teaching Assistant.
Explain concepts clearly and accurately.
Adapt your explanation to the learner's level.
Use examples and step-by-step explanations when helpful.
Use LaTeX for mathematics: $...$ inline and $$...$$ for display math.
"""


def teaching_answer(question):
    return generate_response(
        TEACH_SYSTEM + "\n\nQuestion: " + question,
        temperature=0.3,
        max_tokens=1200,
    )


def run_ai_teaching_assistant():
    st.title("🤖 AI Teaching Assistant")
    st.caption("Ask questions and learn concepts step by step.")

    st.session_state.setdefault("history_ata", [])

    left, right = st.columns([1, 2])

    if left.button("🧹 Clear conversation", key="clear_ata"):
        st.session_state.history_ata = []
        st.rerun()

    if st.session_state.history_ata:
        right.download_button(
            "📄 Export conversation",
            data=export_history(st.session_state.history_ata),
            file_name="teaching_assistant.txt",
            mime="text/plain",
            key="export_ata",
        )

    with st.form("ata_form"):
        question = st.text_area(
            "Enter your question",
            placeholder="Explain photosynthesis in simple terms...",
            height=110,
        )

        submitted = st.form_submit_button(
            "Ask AI",
            use_container_width=True,
        )

    if submitted:
        if not question.strip():
            st.warning("Please enter a question.")
        else:
            with st.spinner("Preparing your explanation..."):
                answer = teaching_answer(question.strip())

            st.session_state.history_ata.append({
                "question": question.strip(),
                "answer": answer,
            })
            st.rerun()

    for i, item in enumerate(st.session_state.history_ata, 1):
        with st.container(border=True):
            st.markdown(f"**Question {i}**")
            st.text(item["question"])
            st.markdown("**Answer**")
            render_answer(item["answer"])


