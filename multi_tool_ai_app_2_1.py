STYLES = {
    "None": "",
    "Photorealistic": ", photorealistic, high detail, natural lighting",
    "Digital art": ", digital art, vibrant colors, detailed",
    "Cartoon": ", friendly cartoon style, bold outlines",
    "Watercolor": ", watercolor painting, soft colors",
    "3D render": ", 3D render, soft studio lighting",
}

BLOCKED_RE = re.compile(
    r"\b("
    r"nude|naked|nsfw|porn\w*|sexual\w*|erotic\w*|fetish|"
    r"gore|gory|mutilat\w*|dismember\w*|behead\w*|"
    r"tortur\w*|suicide|self[- ]harm|bomb[- ]making|"
    r"terroris\w*|child abuse|loli\w*"
    r")\b",
    re.IGNORECASE,
)

MODERATION_PROMPT = """
You are a safety classifier for a school image generator.
Reply with exactly SAFE or UNSAFE.
UNSAFE includes sexual content, graphic violence, self-harm,
hate, illegal instructions, or sexualization of minors.
Prompt:
"""


def check_prompt_safety(prompt):
    if BLOCKED_RE.search(prompt):
        return False, "Please use a family-friendly image description."

    # Fail closed if moderation is unavailable.
    verdict = generate_response(
        MODERATION_PROMPT + prompt,
        temperature=0.0,
        max_tokens=5,
    ).strip().upper()

    if verdict.startswith("UNSAFE"):
        return False, "The prompt was flagged as unsafe."

    if verdict.startswith("SAFE"):
        return True, ""

    return (
        False,
        "Safety verification failed. Check your AI provider and retry.",
    )


def make_image(prompt):
    """
    Uses an online image service.
    Image generation depends on the third-party service being available.
    The prompt is sent to that external service.
    """
    try:
        url = (
            "https://image.pollinations.ai/prompt/"
            + requests.utils.quote(prompt, safe="")
        )

        response = requests.get(
            url,
            params={
                "width": 768,
                "height": 768,
                "nologo": "true",
                "model": "flux",
            },
            timeout=120,
        )

        content_type = response.headers.get("content-type", "")

        if response.ok and content_type.startswith("image/"):
            return response.content, "Pollinations image service"

        return None, (
            f"Image service returned HTTP {response.status_code}. "
            "Try again later."
        )

    except requests.RequestException as e:
        return None, f"Image generation failed: {e}"


def run_safe_ai_image_generator():
    st.title("🎨 Safe AI Image Generator")
    st.caption("Create images from your own descriptions.")

    st.session_state.setdefault("history_img", [])

    if st.button("🧹 Clear image history", key="clear_img"):
        st.session_state.history_img = []
        st.rerun()

    prompt = st.text_area(
        "Describe the image",
        placeholder="A friendly robot teaching math in a sunny classroom",
        height=110,
        key="image_prompt",
    )

    style = st.selectbox(
        "Choose image style",
        list(STYLES.keys()),
    )

    st.caption(
        "Images are generated by an external service. "
        "Do not enter confidential information."
    )

    if st.button("🎨 Generate image", key="generate_img"):
        if not prompt.strip():
            st.warning("Please describe the image.")
        else:
            with st.spinner("Checking prompt safety..."):
                allowed, message = check_prompt_safety(prompt.strip())

            if not allowed:
                st.error(message)
            else:
                with st.spinner("Generating image..."):
                    data, info = make_image(
                        prompt.strip() + STYLES[style]
                    )

                if data is None:
                    st.error(info)
                else:
                    st.session_state.history_img.insert(0, {
                        "prompt": prompt.strip(),
                        "style": style,
                        "png": data,
                        "model": info,
                    })
                    st.rerun()

    for i, item in enumerate(st.session_state.history_img):
        st.divider()

        st.image(
            item["png"],
            caption=(
                f'{item["prompt"]} — {item["style"]} '
                f'({item["model"]})'
            ),
            use_container_width=True,
        )

        st.download_button(
            "⬇️ Download PNG",
            data=item["png"],
            file_name=f"generated_image_{i + 1}.png",
            mime="image/png",
            key=f"download_img_{i}",
        )


