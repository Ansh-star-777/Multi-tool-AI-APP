# 3. MATH FORMATTING
# ============================================================

MATH_RE = re.compile(
    r"(\$\$.+?\$\$|\$[^$\n]+?\$)",
    re.S,
)

DISPLAY_RE = re.compile(
    r"\$\$(.+?)\$\$",
    re.S,
)


def fix_math(text):
    text = re.sub(
        r"\\\[(.+?)\\\]",
        lambda m: "$$" + m.group(1).strip() + "$$",
        text,
        flags=re.S,
    )

    text = re.sub(
        r"\\\((.+?)\\\)",
        lambda m: "$" + m.group(1).strip() + "$",
        text,
        flags=re.S,
    )

    return text


def protect_prose(text):
    parts = MATH_RE.split(text)

    for i in range(0, len(parts), 2):
        parts[i] = re.sub(
            r"(?<=\d)\s*\*(?!\*)\s*(?=\d)",
            r" \\* ",
            parts[i],
        )

    return "".join(parts)


def render_answer(text):
    text = fix_math(text)
    position = 0

    for match in DISPLAY_RE.finditer(text):
        prose = text[position:match.start()]

        if prose.strip():
            st.markdown(protect_prose(prose))

        st.latex(match.group(1).strip())
        position = match.end()

    tail = text[position:]

    if tail.strip():
        st.markdown(protect_prose(tail))


def export_history(history):
    output = []

    for i, item in enumerate(history, 1):
        output.append(f"Question {i}: {item['question']}")
        output.append(f"Answer {i}: {item['answer']}")
        output.append("")

    return "\n".join(output).encode("utf-8")


