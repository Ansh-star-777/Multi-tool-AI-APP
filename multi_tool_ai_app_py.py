# ---------------- Math rendering helpers ----------------
# Matches $$...$$ and $...$ so math segments can be left untouched.
_MATH_RE = re.compile(r"(\$\$.+?\$\$|\$[^$\n]+?\$)", re.S)

def _protect_ops(t):
    """Escape operator characters Markdown would eat, in NON-math text only."""
    # 6871627 * 1287, 6871627*1287, 6871627 *1287
    t = re.sub(r"(?<=\d)[ ]?(?<!\*)\*(?!\*)[ ]?(?=\d)", r" \\* ", t)
    # x * y (spaces on both sides; real italics never look like this)
    t = re.sub(r"(?<=[\w)])(?<!\*) \*(?!\*) (?=[\w(])", r" \\* ", t)
    # a lone ~ would start strikethrough
    t = t.replace("~", r"\~")
    return t

def fix_math(text):
    """Normalize LaTeX delimiters to $...$ / $$...$$."""
    text = re.sub(r"\\\[(.+?)\\\]", lambda m: "$$" + m.group(1).strip() + "$$", text, flags=re.S)
    text = re.sub(r"\\\((.+?)\\\)", lambda m: "$" + m.group(1).strip() + "$", text, flags=re.S)
    # Some models drop the backslashes and leave bare [ ... ] blocks on their own lines
    text = re.sub(r"^\s*\[\s*\n(.+?)\n\s*\]\s*$", lambda m: "$$" + m.group(1).strip() + "$$",
                  text, flags=re.S | re.M)
    return text

_DISPLAY_RE = re.compile(r"\$\$(.+?)\$\$", re.S)

def _protect_prose(t):
    """Escape operators in prose, leaving inline $...$ math untouched."""
    parts = _MATH_RE.split(t)
    for i in range(0, len(parts), 2):
        parts[i] = _protect_ops(parts[i])
    return "".join(parts)

def render_answer(text):
    """Prose -> st.markdown, display math ($$...$$) -> st.latex (never touched by Markdown)."""
    text = fix_math(text)
    pos = 0
    for m in _DISPLAY_RE.finditer(text):
        prose = text[pos:m.start()]
        if prose.strip():
            st.markdown(_protect_prose(prose))
        st.latex(m.group(1).strip())
        pos = m.end()
    tail = text[pos:]
    if tail.strip():
        st.markdown(_protect_prose(tail))

def esc_md(s):
    """Show user text literally: escape inline syntax, line-start operators, keep line breaks."""
    s = re.sub(r"([\\`*_~$|<>])", r"\\\1", str(s))
    s = re.sub(r"(?m)^(\s*)([+\-#=])", r"\1\\\2", s)      # + - # = at line start
    s = re.sub(r"(?m)^(\s*\d+)([.)])", r"\1\\\2", s)      # "1." / "1)" list markers
    return s.replace("\n", "  \n")

